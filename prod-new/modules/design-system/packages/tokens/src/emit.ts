import { MODES } from './types.ts';
import type { BuiltTokens, Mode, ResolvedToken, TokenTable } from './types.ts';

export const VAR_PREFIX = 'ds';

const kebab = (s: string): string => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** `color.text.onAction` -> `--ds-color-text-on-action` */
export function cssVarName(path: string): string {
  return `--${VAR_PREFIX}-${path.split('.').map(kebab).join('-')}`;
}

function family(list: unknown): string {
  if (!Array.isArray(list)) throw new Error('fontFamily must be an array');
  return list.map((f) => (/\s/.test(String(f)) ? `"${String(f)}"` : String(f))).join(', ');
}

function formatByType(type: string, v: unknown): string {
  switch (type) {
    case 'fontFamily':
      return family(v);
    case 'cubicBezier':
      return `cubic-bezier(${(v as readonly number[]).join(', ')})`;
    case 'shadow': {
      const s = v as Record<string, string>;
      return `${s['offsetX']} ${s['offsetY']} ${s['blur']} ${s['spread']} ${s['color']}`;
    }
    default:
      return String(v);
  }
}

const TYPOGRAPHY_PARTS: readonly (readonly [string, string, string])[] = [
  ['fontFamily', 'font-family', 'fontFamily'],
  ['fontSize', 'font-size', 'dimension'],
  ['fontWeight', 'font-weight', 'fontWeight'],
  ['lineHeight', 'line-height', 'number'],
  ['letterSpacing', 'letter-spacing', 'dimension'],
];

/** The CSS declarations one token produces (a typography composite expands to five). */
export function declarations(t: ResolvedToken): readonly (readonly [string, string])[] {
  if (t.type === 'typography') {
    const v = t.value as Record<string, unknown>;
    return TYPOGRAPHY_PARTS.map(([key, suffix, type]) => [`${cssVarName(t.path)}-${suffix}`, formatByType(type, v[key])] as const);
  }
  return [[cssVarName(t.path), formatByType(t.type, t.value)]];
}

/** The single CSS value of a non-composite token. */
export function cssValue(t: ResolvedToken): string {
  const d = declarations(t);
  if (d.length !== 1) throw new Error(`${t.path} is a composite, it has no single CSS value`);
  return (d[0] as readonly [string, string])[1];
}

function block(table: TokenTable, indent: string): string[] {
  return Object.values(table).flatMap((t) => declarations(t).map(([n, v]) => `${indent}${n}: ${v};`));
}

export function toCss(built: BuiltTokens): string {
  const out: string[] = ['/* Generated by @ds-scope/tokens. Do not edit: change src/json/*.json and rebuild. */', ''];
  out.push(':root {', ...block(built.shared, '  '), '}', '');
  out.push(':root,', '[data-theme="light"] {', '  color-scheme: light;', ...block(built.themes.light, '  '), '}', '');
  out.push('[data-theme="dark"] {', '  color-scheme: dark;', ...block(built.themes.dark, '  '), '}', '');
  out.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', '    color-scheme: dark;', ...block(built.themes.dark, '    '), '  }', '}', '');
  return out.join('\n');
}

function valuesOf(table: TokenTable): Record<string, string> {
  const o: Record<string, string> = {};
  for (const t of Object.values(table)) {
    for (const [n, v] of declarations(t)) o[declarations(t).length === 1 ? t.path : n] = v;
  }
  return o;
}

export function toJson(built: BuiltTokens): string {
  const themes = Object.fromEntries(MODES.map((m) => [m, valuesOf(built.themes[m])]));
  return `${JSON.stringify({ shared: valuesOf(built.shared), themes }, null, 2)}\n`;
}

/** A typed module: literal-typed values per path, plus the CSS variable reference of each path. */
export function toTs(built: BuiltTokens): string {
  const lit = (o: Record<string, string>): string => `{\n${Object.entries(o).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n  }`;
  const vars = (table: TokenTable): Record<string, string> =>
    Object.fromEntries(Object.values(table).filter((t) => t.type !== 'typography').map((t) => [t.path, `var(${cssVarName(t.path)})`]));
  const lines = [
    '// Generated by @ds-scope/tokens. Do not edit: change src/json/*.json and rebuild.',
    `export const tokenValues = {`,
    `  shared: ${lit(valuesOf(built.shared))},`,
    `  light: ${lit(valuesOf(built.themes.light))},`,
    `  dark: ${lit(valuesOf(built.themes.dark))},`,
    '} as const;',
    '',
    `export const tokenVars = {`,
    `  shared: ${lit(vars(built.shared))},`,
    `  semantic: ${lit(vars(built.themes.light))},`,
    '} as const;',
    '',
    'export type SharedTokenPath = keyof typeof tokenValues.shared;',
    'export type SemanticTokenPath = keyof typeof tokenValues.light;',
    '',
  ];
  return lines.join('\n');
}

export type { Mode };
